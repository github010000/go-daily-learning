package main

import (
	"fmt"
	"os"
)

// init() 함수는 Go 프로그램이 시작되기 전, 해당 패키지가 로드될 때 자동으로 호출됩니다.
// 이 예제에서는 여러 init() 함수의 실행 순서와 빌드 태그의 개념을 시뮬레이션합니다.

// 첫 번째 초기화 단계: 기본 설정 로딩
// 파일 내에서 함수가 정의된 순서대로 init()이 호출됩니다.
func init() {
	fmt.Println("1. init() 호출: 기본 환경 변수 확인")
}

// 두 번째 초기화 단계: 데이터베이스 연결
// 여러 init() 함수가 정의되어 있을 경우, 코드의 순서대로 실행됩니다.
func init() {
	fmt.Println("2. init() 호출: 데이터베이스 연결 초기화")
}

// 세 번째 초기화 단계: 조건부 초기화 (빌드 태그 시뮬레이션)
// 실제 환경에서는 //go:build linux 와 같은 태그로 파일을 분리하여 컴파일합니다.
// 여기서는 실행 인자를 통해 빌드 태그의 역할을 시뮬레이션합니다.
func init() {
	// os.Args[1] 이 "--mode=prod" 인 경우 프로덕션 환경으로 간주
	if len(os.Args) > 1 && os.Args[1] == "--mode=prod" {
		fmt.Println("3. init() 호출: 프로덕션 모드 전용 설정 적용")
	} else {
		fmt.Println("3. init() 호출: 개발 모드 설정 적용")
	}
}

// main() 함수는 모든 init() 함수가 실행된 이후에 호출됩니다.
// 애플리케이션의 실제 비즈니스 로직을 수행하는 진입점입니다.
func main() {
	fmt.Println("4. main() 함수 시작: 애플리케이션 실행")
	fmt.Println("모든 초기화 단계를 완료했습니다.")
}